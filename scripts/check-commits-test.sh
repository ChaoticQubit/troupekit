#!/bin/sh
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
check="$here/check-commits.sh"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }

repo="$work/repo"
git init -q -b main "$repo"
g() { git -C "$repo" -c user.name=t -c user.email=t@example.com "$@"; }
run() { (cd "$repo" && sh "$check" "$@"); }
c() { g commit -q --allow-empty -m "$1"; }
c "chore: root"
base="$(g rev-parse HEAD)"

for subject in "feat: add a tool" "fix(store-sqlite): close the file" "fix(local,kit): two scopes" "docs(readme)!: drop the old API" \
  "chore(0.3): bump" "ci: pin the runner" "test: cover the queue" "refactor(kit): split the builder" \
  "perf: skip a copy" "build: cargo profile" "style: rustfmt" "revert: feat: add a tool" \
  'Revert "feat: add a tool"' 'Revert "Revert "fix(kit): x""'; do
  c "$subject"
done
g checkout -q -b side
c "feat: on a side branch"
g checkout -q main
g merge -q --no-ff -m "Merge pull request #1 from someone/side" side
run "$base" HEAD >/dev/null 2>&1 || fail "valid range rejected: $(run "$base" HEAD 2>&1)"

for subject in "Add a tool" "feat:no space" "feat add a tool" "feature: add" "Feat: add" \
  "feat(): empty scope" "feat(kit) : space" "fixup! feat: add a tool" "wip" "feat:" \
  'Revert feat: add a tool' 'Revert ""' 'revert "feat: add a tool"' 'Revert "feat: x" now'; do
  good="$(g rev-parse HEAD)"
  c "$subject"
  if out="$(run "$base" HEAD 2>&1)"; then
    fail "bad subject passed: $subject"
  fi
  case "$out" in
    *"$subject"*) ;;
    *) fail "bad subject not named: $subject" ;;
  esac
  g reset -q --hard "$good"
done

nl='
'
for body in "Adds prompt caching for the Anthropic provider." \
  "Prices claude-opus-5-5 and claude-sonnet-5-5 in the catalog." \
  "Routes to Claude Opus or GPT by policy, and reads the Codex model row." \
  "Rows created by cursor iteration keep their order." \
  "Co-Authored-By: Ada Lovelace <ada@example.com>" \
  "Generated with cargo xtask from the catalog." \
  "Signed-off-by: Ada Lovelace <ada@example.com>"; do
  c "feat(providers): vendor work${nl}${nl}${body}"
done
run "$base" HEAD >/dev/null 2>&1 || fail "product mention rejected: $(run "$base" HEAD 2>&1)"

for line in "Co-Authored-By: Claude <noreply@anthropic.com>" \
  "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" \
  "co-authored-by: GitHub Copilot <copilot@github.com>" \
  "Co-authored-by: Cursor Agent <cursoragent@cursor.com>" \
  "Co-Authored-By: Codex <codex@openai.com>" \
  "🤖 Generated with [Claude Code](https://claude.com/claude-code)" \
  "Generated with Claude Code" \
  "Generated by Copilot" \
  "Written with Cursor." \
  "Authored by Codex" \
  "Assisted-by: Claude"; do
  good="$(g rev-parse HEAD)"
  c "fix(kit): a change${nl}${nl}Body text.${nl}${nl}${line}"
  if out="$(run "$base" HEAD 2>&1)"; then
    fail "attribution passed: $line"
  fi
  case "$out" in
    *"$line"*) ;;
    *) fail "attribution not named: $line" ;;
  esac
  g reset -q --hard "$good"
done

for who in "Claude <noreply@anthropic.com>" "Copilot <copilot@github.com>"; do
  good="$(g rev-parse HEAD)"
  name="${who% <*}"
  mail="${who#*<}"
  mail="${mail%>}"
  git -C "$repo" -c user.name="$name" -c user.email="$mail" commit -q --allow-empty -m "fix(kit): by a tool"
  if run "$base" HEAD >/dev/null 2>&1; then
    fail "tool author passed: $who"
  fi
  g reset -q --hard "$good"
done

if run "$base" no-such-ref >/dev/null 2>&1; then
  fail "unknown ref passed"
fi
if run >/dev/null 2>&1; then
  fail "missing arguments passed"
fi
echo "check-commits-test: PASS"
